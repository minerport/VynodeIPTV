type recordingPlayback struct {
	state, reason string // protected by App.mu
	cancel        context.CancelFunc
	done          chan struct{}
}
type recordingPlaybackView struct {
	State     string  `json:"state"`
	Reason    string  `json:"reason"`
	MediaURL  string  `json:"mediaUrl"`
	Available float64 `json:"availableSeconds"`
}

var browserRecordingFile = regexp.MustCompile(`^(browser\.m3u8|browser-[0-9]{8}\.ts)$`)

func (a *App) preparingRecordingsLocked() int {
	count := 0
	for _, p := range a.recordingPlaybacks {
		if p.state == "preparing" {
			count++
		}
	}
	return count
}

// A separate derived copy allows old recordings to use the same browser codecs
// as live TV without changing or deleting the original capture.
func browserRecordingArgs(dir string) []string {
	return []string{"-hide_banner", "-loglevel", "warning", "-nostdin", "-y", "-filter_threads", "2", "-filter_complex_threads", "2",
		"-fflags", "+genpts", "-protocol_whitelist", "file,crypto", "-i", filepath.Join(dir, "recording.m3u8"),
		"-map", "0:v:0?", "-map", "0:a:0?", "-vf", "scale=w='min(1280,iw)':h=-2", "-r", "30",
		"-c:v", "libx264", "-threads", "2", "-preset", "veryfast", "-pix_fmt", "yuv420p", "-crf", "20", "-g", "60", "-keyint_min", "60", "-sc_threshold", "0", "-flags", "+cgop",
		"-af", "aresample=async=1000:first_pts=0", "-c:a", "aac", "-ac", "2", "-ar", "48000", "-b:a", "160k",
		"-f", "hls", "-hls_time", "2", "-hls_list_size", "0", "-hls_playlist_type", "event", "-hls_flags", "independent_segments+temp_file",
		"-hls_segment_filename", filepath.Join(dir, "browser-%08d.ts"), filepath.Join(dir, "browser.m3u8")}
}
func browserRecordingProgress(dir string) (float64, bool) {
	raw, err := os.ReadFile(filepath.Join(dir, "browser.m3u8"))
	if err != nil {
		return 0, false
	}
	seconds := 0.0
	for _, line := range strings.Split(string(raw), "\n") {
		if strings.HasPrefix(line, "#EXTINF:") {
			n, _ := strconv.ParseFloat(strings.TrimSuffix(strings.TrimPrefix(line, "#EXTINF:"), ","), 64)
			seconds += n
		}
	}
	return seconds, strings.Contains(string(raw), "#EXT-X-ENDLIST")
}
func (a *App) recordingPlaybackView(id string) recordingPlaybackView {
	a.mu.Lock()
	p := a.recordingPlaybacks[id]
	v := recordingPlaybackView{State: "idle", MediaURL: fmt.Sprintf("/recorded/%s/browser.m3u8", id)}
	if p != nil {
		v.State = p.state
		v.Reason = p.reason
	}
	a.mu.Unlock()
	v.Available, _ = browserRecordingProgress(filepath.Join(a.recordings, id))
	return v
}
func (a *App) recordingPlaybackRoutes(m *http.ServeMux) {
	m.HandleFunc("POST /api/v1/recordings/{id}/playback", a.auth(false, func(w http.ResponseWriter, r *http.Request) {
		j, ok := a.ownedRecording(w, r)
		if !ok {
			return
		}
		a.mu.Lock()
		// Re-read under the same lock used by recording deletion.
		j, ok = a.recording(j.ID)
		_, capturing := a.recordingLeases[j.ID]
		if !ok || capturing || pendingRecording(j) || j.Bytes == 0 {
			a.mu.Unlock()
			fail(w, 409, "Wait for recording to finish before playback")
			return
		}
		existing := a.recordingPlaybacks[j.ID]
		if existing != nil && existing.state == "preparing" {
			a.mu.Unlock()
			send(w, 200, a.recordingPlaybackView(j.ID))
			return
		}
		dir := filepath.Join(a.recordings, j.ID)
		if seconds, complete := browserRecordingProgress(dir); complete && seconds > 0 && existing != nil && existing.state == "complete" {
			a.mu.Unlock()
			send(w, 200, a.recordingPlaybackView(j.ID))
			return
		}
		// A successful marker is only written after FFmpeg exits normally, not merely
		// because a failed process left ENDLIST on a truncated output.
		if _, err := os.Stat(filepath.Join(dir, "browser.complete")); err == nil {
			if _, complete := browserRecordingProgress(dir); complete {
				done := make(chan struct{})
				close(done)
				a.recordingPlaybacks[j.ID] = &recordingPlayback{state: "complete", done: done}
				a.mu.Unlock()
				send(w, 200, a.recordingPlaybackView(j.ID))
				return
			}
		}
		for _, p := range a.recordingPlaybacks {
			if p.state == "preparing" {
				a.mu.Unlock()
				fail(w, 409, "Another recording is being prepared. Close its player or wait for preparation to finish.")
				return
			}
		}
		if a.closing || len(a.sessions)+len(a.recordingLeases) >= 8 {
			a.mu.Unlock()
			fail(w, 409, "Server worker limit reached or shutting down; stop a live tile before preparing playback")
			return
		}
		if free, err := recordingFreeSpace(dir); err != nil || free < 512*1024*1024 {
			a.mu.Unlock()
			fail(w, 507, "Not enough free recording storage for a browser copy")
			return
		}
		// These paths are generated by this worker and never include source parts.
		files, e := os.ReadDir(dir)
		if e != nil {
			a.mu.Unlock()
			fail(w, 500, "Cannot read recording directory")
			return
		}
		for _, file := range files {
			name := file.Name()
			if browserRecordingFile.MatchString(strings.TrimSuffix(name, ".tmp")) || name == "browser.complete" {
				if err := os.Remove(filepath.Join(dir, name)); err != nil {
					a.mu.Unlock()
					fail(w, 500, "Cannot clear incomplete browser copy")
					return
				}
			}
		}
		ctx, cancel := context.WithCancel(context.Background())
		p := &recordingPlayback{state: "preparing", reason: "Preparing synchronized H.264 / AAC playback", cancel: cancel, done: make(chan struct{})}
		a.recordingPlaybacks[j.ID] = p
		a.mu.Unlock()
		go a.prepareRecordingPlayback(ctx, j.ID, p)
		send(w, 200, a.recordingPlaybackView(j.ID))
	}))
	m.HandleFunc("GET /api/v1/recordings/{id}/playback", a.auth(false, func(w http.ResponseWriter, r *http.Request) {
		j, ok := a.ownedRecording(w, r)
		if ok {
			send(w, 200, a.recordingPlaybackView(j.ID))
		}
	}))
	m.HandleFunc("DELETE /api/v1/recordings/{id}/playback", a.auth(false, func(w http.ResponseWriter, r *http.Request) {
		j, ok := a.ownedRecording(w, r)
		if !ok {
			return
		}
		a.mu.Lock()
		p := a.recordingPlaybacks[j.ID]
		if p != nil && p.state == "preparing" {
			p.cancel()
		}
		a.mu.Unlock()
		if p != nil {
			<-p.done
		}
		send(w, 200, map[string]bool{"ok": true})
	}))
}
func (a *App) prepareRecordingPlayback(ctx context.Context, id string, p *recordingPlayback) {
	defer close(p.done)
	defer p.cancel()
	dir := filepath.Join(a.recordings, id)
	worker, cancel := context.WithCancel(ctx)
	defer cancel()
	cmd := exec.CommandContext(worker, a.ffmpeg, browserRecordingArgs(dir)...)
	cmd.Stdout = io.Discard
	d := &workerDiagnostics{}
	cmd.Stderr = d
	reason := ""
	err := cmd.Start()
	if err == nil {
		done := make(chan error, 1)
		go func() { done <- cmd.Wait() }()
		ticker := time.NewTicker(time.Second)
		defer ticker.Stop()
		last := time.Now()
		previous := 0.0
	loop:
		for {
			select {
			case err = <-done:
				break loop
			case <-ticker.C:
				available, _ := browserRecordingProgress(dir)
				if available > previous {
					previous = available
					last = time.Now()
				}
				if free, e := recordingFreeSpace(dir); e != nil || free < 512*1024*1024 {
					reason = "Browser preparation stopped: recording storage is full or unavailable"
					cancel()
				} else if time.Since(last) > 90*time.Second {
					reason = "Browser preparation stopped: no media progress"
					cancel()
				}
			}
		}
	}
	if ctx.Err() != nil {
		reason = "Browser preparation cancelled; original recording retained"
	} else if err != nil && reason == "" {
		reason = "Could not prepare browser playback: " + d.reason()
	}
	available, complete := browserRecordingProgress(dir)
	if reason == "" && (!complete || available == 0) {
		reason = "No decodable media was produced"
	}
	if reason == "" {
		if os.WriteFile(filepath.Join(dir, "browser.complete"), []byte("h264-aac-v1\n"), 0600) != nil {
			reason = "Could not save browser playback cache"
		}
	}
	a.mu.Lock()
	defer a.mu.Unlock()
	if reason != "" {
		p.state = "failed"
		p.reason = reason
	} else {
		p.state = "complete"
		p.reason = "Browser copy ready; original recording retained"
	}
}
